/**
 * Единая нормализация адресных строк для поиска.
 *
 * Используется в:
 *   - address-flattener.js (при построении search_string из данных сервера);
 *   - address-picker.js    (при обработке ввода пользователя).
 *
 * Раньше логика была продублирована в двух файлах, причём с одним
 * и тем же багом: /\b${w}\b/ в JS опирается на \w (ASCII),
 * кириллица не считается word-char — «\bул\b» не находит «ул» в
 * «ул Ленина». Плюс «п.» в списке стоп-слов попадало в RegExp
 * без экранирования, и точка совпадала с любым символом.
 */

// Список стоп-слов (синхронизирован по смыслу с UI-фильтрами адреса)
const STOP_WORDS = [
  "ул",
  "улица",
  "пр",
  "проспект",
  "пр-т",
  "пер",
  "переулок",
  "ш",
  "шоссе",
  "б-р",
  "бульвар",
  "пл",
  "площадь",
  "д",
  "дом",
  "п",
  "под",
  "подъезд",
  "лифт",
  "п.",
  "авеню",
  "аллея",
];

/**
 * Экранирование спецсимволов RegExp.
 * Критично для "п." (точка = любой символ), "пр-т", "б-р".
 */
function escapeRegExp(str) {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Один скомпилированный RegExp на все стоп-слова.
 *
 * Границы через (?:^|\s) ... (?=\s|$), а не \b:
 *   \b в JS = между \w и не-\w, где \w = [A-Za-z0-9_].
 *   Кириллица не \w — границы вокруг «ул» не находятся.
 *   Явные пробелы работают для любого алфавита.
 *
 * Сортировка по убыванию длины — «улица» применяется раньше «ул»,
 * чтобы длинное стоп-слово не резалось коротким (страховка: с
 * точными границами это не обязательно, но предсказуемее).
 */
const STOP_WORDS_RE = new RegExp(
  "(?:^|\\s)(?:" +
    STOP_WORDS.slice()
      .sort((a, b) => b.length - a.length)
      .map(escapeRegExp)
      .join("|") +
    ")(?=\\s|$)",
  "g",
);

/**
 * Нормализовать строку для поиска: lowercase, убрать пунктуацию,
 * вырезать стоп-слова, схлопнуть пробелы.
 *
 * Примеры:
 *   "ул. Красноармейская д. 2"  → "красноармейская 2"
 *   "пр. Буденновский, 15г"     → "буденновский 15г"
 *   "Ленина проспект 5"         → "ленина 5"
 */
export function normalizeSearchString(text) {
  if (!text) return "";

  let t = text
    .toLowerCase()
    // Пунктуация → пробел (не «удалить», иначе «ул.ленина»
    // превратится в «уллеленина» и не разрежется на слова).
    .replace(/[^\wа-яё\s]/gi, " ")
    .replace(/\s+/g, " ")
    .trim();

  // Один проход вместо 22 replace(). Заменяем на пробел (не «»),
  // чтобы соседние слова не склеились.
  t = t.replace(STOP_WORDS_RE, " ");

  return t.replace(/\s+/g, " ").trim();
}
