<?php

declare(strict_types=1);

namespace App\Support;

/**
 * Область чтения заявок — единая точка истины для списков и карточки.
 *
 * Зачем отдельный класс: формула «видит всё» была продублирована трижды
 * (listOpen, listClosed, findByIdDetailed), а проверка назначенности —
 * дважды. Правка матрицы чтения неизбежно расходилась бы между списком
 * и карточкой: механик открывал по ссылке заявку, которой нет в списке.
 *
 * ИНВАРИАНТ: видимость в списке = видимость карточки. Оба пути спрашивают
 * readAll()/canView() здесь и не выводят роль заново.
 *
 * Разделение с CallPolicy: здесь ЧТЕНИЕ, там ЗАПИСЬ. Смешивать нельзя —
 * can_edit раньше считался от readAll, и флаг чтения выдавал бы механику
 * редактирование. Права на действия считает только CallPolicy.
 *
 * Класс чистый: bool, без БД и исключений. readAll() — решение по
 * пользователю; isAssigned()/canView() работают со строкой lift_calls и
 * знают имена слотов ответственных (контракт строки, не SQL). WHERE для
 * списков строит репозиторий по readAll() — в одном приватном методе,
 * чтобы фильтр не жил в двух копиях.
 *
 * === КАК РАСШИРЯТЬ (точки помечены в коде маркерами) ===
 * A. Группы лифтов (bisness.md §3.1, §5.1): «все» станет «все в доступных
 *    группах». Добавляется метод allowedGroupIds(array $user): ?array
 *    (null = без ограничения) и фильтр по elevator_group_id в
 *    репозитории. readAll() при этом остаётся «видит весь тенант».
 * B. Закреплённые лифты (user_elevator_assignment): для закрытых заявок
 *    механик видит «свои лифты + свои заявки». Второй источник «своих»
 *    добавляется в canView(), сигнатура уже принимает $call.
 * C. Доп. права на чтение из extra_permissions — по образцу CallPolicy:
 *    аддитивный слой, транспорт поля делает AuthService::formatUser.
 *
 * ЗАМЕТКА ДЛЯ РЕФАКТОРИНГА: комментарии этого файла — зафиксированные
 * решения, а не пересказ синтаксиса. Код восстанавливается из тестов,
 * решения — нет. Комментарии СОХРАНЯТЬ и переносить вместе с логикой;
 * удалять только вместе с той логикой, к которой они относятся.
 */
final class CallScope
{
    private const string ROLE_ADMIN = 'administrator';
    private const string ROLE_DISPATCHER = 'dispatcher';

    /**
     * Слоты ответственных в строке lift_calls.
     *
     * Все три участвуют и в фильтре списка, и в проверке карточки:
     * механик во втором или третьем слоте иначе терял бы заявку из
     * собственного списка. Список слотов держим в одном месте — раньше
     * он был вписан литералами в four местах репозитория.
     */
    private const array STAFF_FIELDS = ['call_staff', 'call_staff2', 'call_staff3'];

    /**
     * Видит ли пользователь заявки всего тенанта.
     *
     * Флаг намеренно НЕ привязан к словарю ролей (решение A): право
     * уважается у любого аккаунта, не только engineer. Прораб обычно
     * уже dispatcher после нормализации AuthService, но легаси-записи
     * приходят с другими ролями — привязка к 'engineer' оставила бы их
     * без области чтения при миграции.
     *
     * Флаг даёт только ЧТЕНИЕ и выдаётся админом. Guest с флагом тоже
     * получает чтение всего — это осознанное следствие формулы A
     * (admin ∥ dispatcher ∥ флаг). Если понадобится исключить guest,
     * исключение добавляется ОДНОЙ строкой перед return, а не правкой
     * вызывающих мест.
     *
     * РАСШИРЕНИЕ A: метод остаётся «весь тенант», групповое ограничение
     * живёт отдельно — иначе два разных смысла у одного предиката.
     */
    public static function readAll(array $user): bool
    {
        $role = (string) ($user['role'] ?? '');

        if ($role === self::ROLE_ADMIN || $role === self::ROLE_DISPATCHER) {
            return true;
        }

        // Поле транспортирует AuthService::formatUser. Без него флаг
        // читается как 0 и область чтения молча сужается до «свои».
        return (int) ($user['user_read_all_calls'] ?? 0) === 1;
    }

    /**
     * Назначен ли пользователь ответственным в любом из трёх слотов.
     *
     * 0 и NULL в слоте одинаково означают «не назначен», поэтому пустой
     * слот приводится к 0. Проверка $uid > 0 обязательна: без неё
     * пользователь с id 0 (битая сессия, легаси-запись) совпал бы с
     * каждым пустым слотом и получил все заявки разом.
     *
     * РАСШИРЕНИЕ B: «свои» перестанут быть только назначенностью —
     * добавятся закреплённые лифты. Тело метода, сигнатура та же.
     */
    public static function isAssigned(array $user, array $call): bool
    {
        $uid = (int) ($user['id'] ?? 0);

        if ($uid <= 0) {
            return false;
        }

        foreach (self::STAFF_FIELDS as $field) {
            if ((int) ($call[$field] ?? 0) === $uid) {
                return true;
            }
        }

        return false;
    }

    /**
     * Доступ к конкретной заявке — тот же критерий, что и в списке.
     *
     * Карточка обязана спрашивать именно этот метод: отдельная проверка
     * в findByIdDetailed уже приводила к расхождению с фильтром списка.
     * Отказ выражается null-ответом (§12.2), а не 403 — существование
     * заявки не раскрывается.
     *
     * РАСШИРЕНИЕ B/C: новые источники «своих» и доп. права подключаются
     * здесь, вызывающие места не меняются.
     */
    public static function canView(array $user, array $call): bool
    {
        return self::readAll($user) || self::isAssigned($user, $call);
    }
}