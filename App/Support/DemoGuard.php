<?php

declare(strict_types=1);

namespace App\Support;

/**
 * Демонстрационный тенант: признак и право на изменение учётной записи.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ КЛАСС: на демо все учётки общие — admin, dispatcher,
 * mechanic, guest. Смена пароля одним посетителем запирает вход остальным,
 * а смена ФИО подменяет автора во всех заявках и заметках. Решение
 * «здесь нельзя менять профиль» обязано быть ОДНИМ: флаг can_edit_profile
 * в config и проверка в будущем save_user_settings спрашивают один
 * предикат. Две копии разошлись бы — ровно тот дефект, от которого
 * CallPolicy уводит права на заявки.
 *
 * КЛАСС ЧИСТЫЙ: только bool, без БД, исключений и суперглобалов —
 * как CallPolicy и CallScope. ConfigService зовёт его на каждый config;
 * запрос в БД здесь был бы и лишним расходом, и вторым источником истины.
 *
 * ЧТО ЗАПРЕЩЕНО: пароль и ФИО (user_password, user_name, user_surname,
 * user_firstname, user_patronymic).
 *
 * ЧТО НЕ ЗАПРЕЩЕНО — решения, а не недосмотр:
 *   - column_settings: порядок и видимость колонок персональны и
 *     безвредны, их сохранение обязано продолжать работать;
 *   - автомиграция хэша в AuthService::login() → updatePasswordHash().
 *     Это не действие пользователя, а апгрейд MD5 → bcrypt при успешном
 *     входе. Запрет обесточит вход всем легаси-учёткам с MD5 — защита
 *     пароля ценой отказа входа. Гейтить нужно ДЕЙСТВИЕ, а не запись
 *     в колонку: иначе первый же вызов репозитория из login попадёт под удар.
 *
 * СОСТОЯНИЕ НА СЕЙЧАС: ни ApiController, ни AuthController не содержат
 * экшена записи профиля (save_user_settings отсутствует в match, §13
 * протокола это подтверждает). Предикат пока обслуживает только выдачу
 * флага клиенту. Когда эндпоинт появится, проверка встаёт ДО любой записи
 * и спрашивает canEditProfile() — клиентский disabled обходится через
 * DevTools за десять секунд, UX защитой не является.
 *
 * РАСШИРЕНИЕ: новый демо-тенант — одна строка в DEMO_TENANTS.
 */
final class DemoGuard
{
    /**
     * Демо-тенанты: поддомен => имя БД.
     *
     * ДВА атрибута, а не один. Поддомен — публичная идентичность:
     * по нему ключуют состояние OrgKeyGuard и ExportRateLimiter.
     * Имя БД — проверяемый факт соединения. Переименование любого
     * из них не должно МОЛЧА выключать защиту, поэтому совпадения
     * по любому достаточно. Один атрибут дал бы fail-open на ровном
     * переезде, и заметили бы это по сменённому паролю, а не по логу.
     *
     * Поддомен приводится к нижнему регистру: Tenant снижает Host
     * до поиска в реестре (§18.1). Имя БД НЕ приводится: на Linux
     * имена баз регистрозависимы, «Demo» и «demo» — разные базы.
     *
     * Маркер lift_options.demo_seed_allowed сюда НЕ подключается:
     * он разрешает генератору удалить все заявки — другое решение.
     * Один флаг на два права означал бы, что выключение пересева
     * разрешает смену пароля общего аккаунта.
     */
    private const array DEMO_TENANTS = [
        'demo' => 'zamotaev_demo_liftcs',
    ];

    /**
     * Это демонстрационный тенант?
     *
     * Пустые идентификаторы → false: вопрос фактический, «неизвестно»
     * не равно «демо». Право на запись решает canEditProfile(), и у него
     * другой дефолт — смешивать два вопроса в одном методе нельзя.
     *
     * Публичный: признак нужен не только правам — на нём можно построить
     * баннер «Демо-режим» или отказ от опасных действий в админке.
     */
    public static function isDemo(string $tenantId, string $dbName = ''): bool
    {
        // strtolower, не mb_: поддомен ограничен /^[a-z0-9][a-z0-9-]{0,30}$/
        // (§18.1), не-ASCII сюда не доходит и дороже обходиться незачем.
        $id = strtolower(trim($tenantId));
        $db = trim($dbName);

        if ($id !== '' && isset(self::DEMO_TENANTS[$id])) {
            return true;
        }

        return $db !== '' && in_array($db, self::DEMO_TENANTS, true);
    }

    /**
     * Разрешено ли менять пароль и ФИО.
     *
     * Запрет на ВЕСЬ тенант, а не на роль: на демо общие все учётки,
     * включая administrator. Исключение для админа вернуло бы дыру —
     * именно админ меняет пароль себе и запирает остальных.
     *
     * Пустые идентификаторы → ЗАПРЕТ (deny by default, как CallPolicy::roleOf
     * трактует пустую роль как guest). Разрешать запись, не зная в каком
     * тенанте, нельзя. Сегодня недостижимо: Tenant::fromRequest бросает
     * исключение на нерезолвленном хосте, а ConfigService держит готовый
     * объект — но дефолт обязан быть безопасным на будущее.
     *
     * Раздельность с column_settings намеренна: метод отвечает только
     * за учётную запись. Один общий «can_edit_settings» заблокировал бы
     * и персональные настройки колонок, которые на демо менять можно.
     */
    public static function canEditProfile(string $tenantId, string $dbName = ''): bool
    {
        if (trim($tenantId) === '' && trim($dbName) === '') {
            return false;
        }

        return !self::isDemo($tenantId, $dbName);
    }
}