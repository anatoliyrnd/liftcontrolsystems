    //
    // Длина префикса 16 символов — валидация details ≥ 6 проходит
    // даже при полностью пустом остатке. Отдельное «дополнение
    // короткого описания» не нужно.
    //
    // Формат сборки: "<префикс>. <остаток>", при пустом остатке —
